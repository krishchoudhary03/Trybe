const DAY = 86_400_000;

/** Sample listings. Dates are relative to `now` so the demo never goes stale. These are demo data, not real postings. */
export function buildSampleOpportunities(now: Date = new Date()): Opportunity[] {
  const day = (offset: number) => {
    const d = new Date(now.getTime() + offset * DAY);
    d.setHours(23, 59, 0, 0);
    return d.toISOString();
  };
  return SEEDS.map(({ deadlineInDays, postedDaysAgo, ...rest }) => ({
    ...rest,
    deadline: deadlineInDays === undefined ? undefined : day(deadlineInDays),
    postedAt: new Date(now.getTime() - postedDaysAgo * DAY).toISOString(),
    source: 'sample' as const,
  }));
}
